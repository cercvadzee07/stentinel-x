"use client";

import { BellOff, CheckSquare, ExternalLink, MessageSquare, Search, Siren, Square, UserPlus } from "lucide-react";
import Link from "next/link";
import { useRouter, useSearchParams } from "next/navigation";
import { Suspense, useCallback, useEffect, useMemo, useState } from "react";
import { deniedHint, useSession } from "@/components/session";
import { EventDrawer, EventTable } from "@/components/events";
import { useLive } from "@/components/live";
import {
  Button, Drawer, Empty, ErrorState, Field, Input, KV, Modal, PageHeader, Panel, Select, SevBadge, Skeleton, StatusBadge, Tabs, Tag, Textarea, useToast,
} from "@/components/ui";
import { CreateIncident, useAnalysts } from "@/components/triage";
import { api, cx, fmtDateTime, fmtNum, relTime } from "@/lib/client";
import { and, term } from "@/lib/query";
import { ALERT_STATUSES, ALERT_STATUS_LABEL, SEVERITIES, type Alert, type AlertStatus, type DetectionRule, type SecurityEvent, type Severity } from "@/lib/types";

export default function Page() {
  return <Suspense fallback={<Skeleton className="h-96" />}><Alerts /></Suspense>;
}

function Alerts() {
  const params = useSearchParams();
  const router = useRouter();
  const toast = useToast();
  const analysts = useAnalysts();
  const { can } = useSession();
  const write = can("alerts:write");
  const { alertVersion } = useLive();
  const [items, setItems] = useState<Alert[] | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [status, setStatus] = useState<AlertStatus[]>(["new", "investigating", "escalated"]);
  const [sev, setSev] = useState<Severity[]>(params.get("severity") ? [params.get("severity") as Severity] : []);
  const [q, setQ] = useState(params.get("q") ?? "");
  const [showSuppressed, setShowSuppressed] = useState(false);
  const [selected, setSelected] = useState<Set<string>>(new Set());
  const [incidentFor, setIncidentFor] = useState<string[] | null>(null);
  const openId = params.get("id");

  const load = useCallback(() => {
    const p = new URLSearchParams({ status: status.join(","), severity: sev.join(","), q, suppressed: showSuppressed ? "1" : "0" });
    return api<{ items: Alert[] }>(`/api/alerts?${p}`).then((r) => { setItems(r.items); setErr(null); }).catch((e) => setErr(e.message));
  }, [status, sev, q, showSuppressed]);
  useEffect(() => { load(); }, [load, alertVersion]);

  const setOpen = (id: string | null) => router.replace(id ? `/alerts?id=${id}` : "/alerts", { scroll: false });
  const toggleSel = (id: string) => write && setSelected((s) => { const n = new Set(s); n.has(id) ? n.delete(id) : n.add(id); return n; });
  const allSel = !!items?.length && items.every((a) => selected.has(a.id));

  const bulk = async (patch: Record<string, unknown>, label: string) => {
    const ids = [...selected];
    try {
      const r = await api<{ updated: number }>("/api/alerts/bulk", { method: "POST", json: { ids, patch } });
      toast({ tone: "success", title: `${label}: ${r.updated} alert(s)` });
      setSelected(new Set()); load();
    } catch (e) { toast({ tone: "error", title: "Bulk action failed", body: (e as Error).message }); }
  };

  const counts = useMemo(() => {
    const c: Record<string, number> = {};
    items?.forEach((a) => { c[a.severity] = (c[a.severity] ?? 0) + 1; });
    return c;
  }, [items]);

  return (
    <div>
      <PageHeader title="Security Alerts" subtitle="Generated by the correlation engine. Repeat detections merge into the open alert for the same rule and key."
        actions={<Input placeholder="Search id, IP, asset, rule, analyst…" value={q} onChange={(e) => setQ(e.target.value)} className="w-72" aria-label="Search alerts" />} />

      <Panel bodyClass="p-3" className="mb-3">
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-[11px] uppercase tracking-wider text-ink-3">Status</span>
          {ALERT_STATUSES.map((s) => (
            <button key={s} aria-pressed={status.includes(s)} onClick={() => setStatus((xs) => (xs.includes(s) ? xs.filter((x) => x !== s) : [...xs, s]))}
              className={cx("transition-opacity", !status.includes(s) && "opacity-35")}><StatusBadge s={s} /></button>
          ))}
          <span className="ml-3 text-[11px] uppercase tracking-wider text-ink-3">Severity</span>
          {SEVERITIES.slice(1).map((s) => (
            <button key={s} aria-pressed={sev.includes(s)} onClick={() => setSev((xs) => (xs.includes(s) ? xs.filter((x) => x !== s) : [...xs, s]))}
              className={cx("flex items-center gap-1 transition-opacity", sev.length > 0 && !sev.includes(s) && "opacity-35")}><SevBadge s={s} /><span className="text-[10.5px] text-ink-3 tnum">{counts[s] ?? 0}</span></button>
          ))}
          <label className="ml-auto flex items-center gap-1.5 text-[12px] text-ink-2"><input type="checkbox" className="accent-emerald" checked={showSuppressed} onChange={(e) => setShowSuppressed(e.target.checked)} />Show suppressed</label>
        </div>
      </Panel>

      {write && selected.size > 0 && (
        <div className="glass glow-emerald sticky top-16 z-20 mb-3 flex flex-wrap items-center gap-2 rounded-xl px-3 py-2">
          <span className="text-[13px] font-medium">{selected.size} selected</span>
          <Select aria-label="Bulk assign" defaultValue="" onChange={(e) => { if (e.target.value) bulk({ assignee: e.target.value }, `Assigned to ${e.target.value}`); e.target.value = ""; }}>
            <option value="">Assign to…</option>{analysts.map((a) => <option key={a}>{a}</option>)}
          </Select>
          <Select aria-label="Bulk status" defaultValue="" onChange={(e) => { if (e.target.value) bulk({ status: e.target.value }, `Status → ${ALERT_STATUS_LABEL[e.target.value as AlertStatus]}`); e.target.value = ""; }}>
            <option value="">Set status…</option>{ALERT_STATUSES.map((s) => <option key={s} value={s}>{ALERT_STATUS_LABEL[s]}</option>)}
          </Select>
          <Button size="sm" onClick={() => bulk({ suppressed: true }, "Suppressed")}><BellOff className="h-3.5 w-3.5" />Suppress</Button>
          <Button size="sm" variant="primary" onClick={() => setIncidentFor([...selected])}><Siren className="h-3.5 w-3.5" />Create incident</Button>
          <Button size="sm" variant="ghost" onClick={() => setSelected(new Set())}>Clear</Button>
        </div>
      )}

      {err && <ErrorState message={err} onRetry={load} />}
      <Panel bodyClass="p-0" title={items ? `${fmtNum(items.length)} alerts` : "Alerts"}>
        {!items ? <div className="space-y-2 p-4">{Array.from({ length: 8 }, (_, i) => <Skeleton key={i} className="h-10" />)}</div>
          : items.length === 0 ? <Empty title="No alerts match these filters" body="Launch an attack scenario from the Simulator menu to watch detections arrive." /> : (
          <div className="max-h-[calc(100vh-330px)] overflow-auto scrollbar-thin">
            <table className="w-full text-[12.5px]">
              <thead className="sticky top-0 z-10 bg-panel/95 backdrop-blur"><tr className="border-b border-line text-left text-[10.5px] uppercase tracking-wider text-ink-3">
                <th className="px-3 py-2"><button aria-label="Select all" disabled={!write} title={write ? undefined : deniedHint("alerts:write")} onClick={() => setSelected(allSel ? new Set() : new Set(items.map((a) => a.id)))}>{allSel ? <CheckSquare className="h-4 w-4 text-emerald" /> : <Square className="h-4 w-4" />}</button></th>
                {["Alert", "Severity", "Source → Target", "Asset", "Rule / MITRE", "Events", "First seen", "Last seen", "Status", "Analyst"].map((h) => <th key={h} className="px-3 py-2 font-medium whitespace-nowrap">{h}</th>)}
              </tr></thead>
              <tbody>
                {items.map((a) => (
                  <tr key={a.id} onClick={() => setOpen(a.id)} className={cx("cursor-pointer border-b border-line/40 hover:bg-emerald/[0.04]", a.severity === "critical" && "bg-sev-critical/[0.05]", openId === a.id && "bg-emerald/[0.08]", a.suppressed && "opacity-50")}>
                    <td className="px-3" onClick={(e) => { e.stopPropagation(); toggleSel(a.id); }}>{selected.has(a.id) ? <CheckSquare className="h-4 w-4 text-emerald" /> : <Square className="h-4 w-4 text-ink-3" />}</td>
                    <td className="px-3 py-2 max-w-[280px]"><div className="truncate text-ink">{a.title}</div><div className="flex items-center gap-1.5 font-mono text-[10.5px] text-ink-3">{a.id}{a.incidentId && <Tag className="text-sev-high">{a.incidentId}</Tag>}{a.suppressed && <Tag>suppressed</Tag>}</div></td>
                    <td className="px-3"><SevBadge s={a.severity} glow /></td>
                    <td className="px-3 font-mono text-[11.5px] whitespace-nowrap">{a.sourceIp} <span className="text-ink-3">→</span> {a.targetIp}</td>
                    <td className="px-3 text-ink-2">{a.asset ?? "—"}</td>
                    <td className="px-3"><div className="text-ink-2 whitespace-nowrap">{a.ruleName}</div><div className="font-mono text-[10.5px] text-ink-3">{a.mitre.map((m) => m.split(" ")[0]).join(", ")}</div></td>
                    <td className="px-3 font-mono tnum">{fmtNum(a.eventCount)}</td>
                    <td className="px-3 text-ink-3 whitespace-nowrap">{fmtDateTime(a.firstSeen)}</td>
                    <td className="px-3 text-ink-2 whitespace-nowrap">{relTime(a.lastSeen)}</td>
                    <td className="px-3"><StatusBadge s={a.status} /></td>
                    <td className="px-3 text-ink-2 whitespace-nowrap">{a.assignee ?? <span className="text-ink-3">unassigned</span>}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Panel>

      <AlertDrawer id={openId} onClose={() => setOpen(null)} analysts={analysts} onChanged={load} onIncident={(id) => setIncidentFor([id])} />
      <CreateIncident ids={incidentFor} onClose={() => setIncidentFor(null)} analysts={analysts} alerts={items ?? []}
        onCreated={(id) => { setIncidentFor(null); setSelected(new Set()); router.push(`/incidents?id=${id}`); }} />
    </div>
  );
}

interface AlertDetail { alert: Alert; events: SecurityEvent[]; rule: DetectionRule | null; agedOut: number }

function AlertDrawer({ id, onClose, analysts, onChanged, onIncident }: { id: string | null; onClose: () => void; analysts: string[]; onChanged: () => void; onIncident: (id: string) => void }) {
  const toast = useToast();
  const { can } = useSession();
  const write = can("alerts:write");
  const lock = write ? {} : { disabled: true, title: deniedHint("alerts:write") };
  const { alertVersion } = useLive();
  const [d, setD] = useState<AlertDetail | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [tab, setTab] = useState<"overview" | "events" | "activity">("overview");
  const [comment, setComment] = useState("");
  const [event, setEvent] = useState<string | null>(null);

  const load = useCallback(() => { if (id) api<AlertDetail>(`/api/alerts/${id}`).then((x) => { setD(x); setErr(null); }).catch((e) => setErr(e.message)); }, [id]);
  useEffect(() => { setD(null); setTab("overview"); load(); }, [id, load]);
  useEffect(() => { load(); }, [alertVersion, load]);

  const patch = async (p: Record<string, unknown>, msg: string) => {
    try { await api(`/api/alerts/${id}`, { method: "PATCH", json: p }); toast({ tone: "success", title: msg }); load(); onChanged(); }
    catch (e) { toast({ tone: "error", title: "Update failed", body: (e as Error).message }); }
  };

  const a = d?.alert;
  const huntQuery = a && d?.rule ? and(d.rule.logic.filter, a.sourceIp ? term("source.ip", a.sourceIp) : "") : a ? term("source.ip", a.sourceIp ?? "") : "";
  return (
    <>
      <Drawer open={!!id} onClose={onClose} width={820}
        title={a ? <span className="flex items-center gap-2"><SevBadge s={a.severity} glow />{a.title}</span> : "Alert"}
        subtitle={a && <span className="font-mono">{a.id} · {a.ruleName} · last seen {relTime(a.lastSeen)}</span>}
        actions={a && !a.incidentId && can("incidents:write") && <Button size="sm" variant="primary" onClick={() => onIncident(a.id)}><Siren className="h-3.5 w-3.5" />Create incident</Button>}>
        {err && <div className="p-5"><ErrorState message={err} /></div>}
        {!a && !err && <div className="space-y-2 p-5">{Array.from({ length: 10 }, (_, i) => <Skeleton key={i} className="h-7" />)}</div>}
        {a && d && (
          <div className="p-5">
            <div className="mb-4 grid gap-2 sm:grid-cols-4">
              <Field label="Status"><Select {...lock} value={a.status} onChange={(e) => patch({ status: e.target.value }, `Status → ${ALERT_STATUS_LABEL[e.target.value as AlertStatus]}`)}>{ALERT_STATUSES.map((s) => <option key={s} value={s}>{ALERT_STATUS_LABEL[s]}</option>)}</Select></Field>
              <Field label="Assigned analyst"><Select {...lock} value={a.assignee ?? ""} onChange={(e) => patch({ assignee: e.target.value || null }, e.target.value ? `Assigned to ${e.target.value}` : "Unassigned")}><option value="">Unassigned</option>{analysts.map((x) => <option key={x}>{x}</option>)}</Select></Field>
              <Field label="Severity"><Select {...lock} value={a.severity} onChange={(e) => patch({ severity: e.target.value }, `Severity → ${e.target.value}`)}>{SEVERITIES.map((s) => <option key={s}>{s}</option>)}</Select></Field>
              <Field label="Suppression"><Button {...lock} onClick={() => patch({ suppressed: !a.suppressed }, a.suppressed ? "Alert unsuppressed" : "Alert suppressed — further matches are dropped")} variant={a.suppressed ? "primary" : "outline"}><BellOff className="h-3.5 w-3.5" />{a.suppressed ? "Unsuppress" : "Suppress"}</Button></Field>
            </div>
            {a.incidentId && <Link href={`/incidents?id=${a.incidentId}`} className="mb-4 flex items-center gap-2 rounded-lg border border-sev-high/40 bg-sev-high/5 px-3 py-2 text-[12.5px] hover:border-sev-high/70"><Siren className="h-4 w-4 text-sev-high" />Linked to incident <span className="font-mono">{a.incidentId}</span><ExternalLink className="ml-auto h-3.5 w-3.5" /></Link>}
            <div className="mb-3"><Tabs value={tab} onChange={setTab} items={[{ value: "overview", label: "Details" }, { value: "events", label: `Related events (${d.events.length})` }, { value: "activity", label: `Activity (${a.comments.length + a.history.length})` }]} /></div>

            {tab === "overview" && (
              <div>
                <KV k="alert.id" v={a.id} /><KV k="rule" v={`${a.ruleName} (${a.ruleId})`} mono={false} />
                <KV k="source.ip" v={a.sourceIp} /><KV k="target.ip" v={a.targetIp} /><KV k="related.asset" v={a.asset} />
                <KV k="correlation.key" v={a.groupKey} /><KV k="first_seen" v={fmtDateTime(a.firstSeen)} /><KV k="last_seen" v={fmtDateTime(a.lastSeen)} />
                <KV k="event.count" v={fmtNum(a.eventCount)} />
                <KV k="mitre.attack" v={<span className="flex flex-wrap gap-1">{a.mitre.map((m) => <a key={m} target="_blank" rel="noreferrer" href={`https://attack.mitre.org/techniques/${m.split(" ")[0].replace(".", "/")}/`} className="hover:text-emerald"><Tag className="font-mono">{m}</Tag></a>)}</span>} />
                {d.rule && <div className="mt-4 rounded-lg border border-line bg-base/60 p-3 font-mono text-[11.5px]">
                  <div className="mb-1 text-[10.5px] uppercase tracking-wider text-ink-3">Detection logic</div>
                  <span className="text-ink-3">WHEN </span><span className="text-cyan">{d.rule.logic.filter}</span><br />
                  <span className="text-ink-3">GROUP BY </span>{d.rule.logic.groupBy.join(", ")}<br />
                  <span className="text-ink-3">ALERT IF </span>{d.rule.logic.aggregate}{d.rule.logic.distinctField ? `(${d.rule.logic.distinctField})` : ""} ≥ {fmtNum(d.rule.logic.threshold)} within {d.rule.logic.windowSec}s
                </div>}
                <div className="mt-4 flex flex-wrap gap-2">
                  <Link href={`/log-explorer?q=${encodeURIComponent(huntQuery)}&from=${a.firstSeen - 60_000}&to=${a.lastSeen + 60_000}`}><Button size="sm"><Search className="h-3.5 w-3.5" />Hunt in Log Explorer</Button></Link>
                  {a.sourceIp && <Link href={`/log-explorer?q=${encodeURIComponent(`source.ip:${a.sourceIp} OR destination.ip:${a.sourceIp}`)}`}><Button size="sm"><Search className="h-3.5 w-3.5" />All activity of {a.sourceIp}</Button></Link>}
                </div>
              </div>
            )}

            {tab === "events" && (
              <div className="-mx-5">
                {d.agedOut > 0 && <p className="px-5 pb-2 text-[11.5px] text-sev-medium">{d.agedOut} contributing event(s) aged out of the in-memory retention buffer.</p>}
                <EventTable events={[...d.events].reverse()} onOpen={(e) => setEvent(e.id)} cols={["time", "severity", "type", "src", "dst", "user", "action", "count"]} dense />
              </div>
            )}

            {tab === "activity" && (
              <div>
                {write && <div className="mb-4 flex gap-2">
                  <Textarea rows={2} value={comment} onChange={(e) => setComment(e.target.value)} placeholder="Add an analyst comment…" className="flex-1" />
                  <Button variant="primary" disabled={!comment.trim()} onClick={() => { patch({ comment }, "Comment added"); setComment(""); }}><MessageSquare className="h-3.5 w-3.5" />Post</Button>
                </div>}
                <ol className="relative space-y-3 border-l border-line pl-4">
                  {[...a.comments.map((c) => ({ at: c.at, who: c.author, what: "commented", text: c.text })), ...a.history.map((h) => ({ at: h.at, who: h.actor, what: h.action, text: h.detail }))]
                    .sort((x, y) => y.at - x.at).map((x, i) => (
                      <li key={i} className="relative">
                        <span className={cx("absolute -left-[21px] top-1 h-2.5 w-2.5 rounded-full border-2 border-panel", x.what === "commented" ? "bg-cyan" : x.what === "created" ? "bg-emerald" : "bg-ink-3")} />
                        <div className="text-[12px]"><span className="text-ink">{x.who}</span> <span className="text-ink-3">{x.what}</span> <span className="text-[11px] text-ink-3">· {fmtDateTime(x.at)}</span></div>
                        {x.text && <div className={cx("mt-0.5 text-[12.5px]", x.what === "commented" ? "rounded-md border border-line bg-base/60 px-2.5 py-1.5 text-ink-2" : "font-mono text-[11.5px] text-ink-3")}>{x.text}</div>}
                      </li>
                    ))}
                </ol>
              </div>
            )}
          </div>
        )}
      </Drawer>
      <EventDrawer id={event} onClose={() => setEvent(null)} onOpen={(e) => setEvent(e.id)} />
    </>
  );
}
